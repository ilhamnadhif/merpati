struct Viewer {
    samples: Vec<Sample>,
    current: usize,
    doc: Result<Document, Error>,
    last_link: Option<String>,
    shots: Option<Shots>,
}

/// Automatic screenshots of every sample in both themes.
struct Shots {
    dir: PathBuf,
    step: usize,
    frames: u32,
    requested: bool,
    done: Arc<AtomicUsize>,
}

impl Viewer {
    fn select(&mut self, i: usize) {
        self.current = i;
        let s = &self.samples[i];
        self.doc = parse(&s.template, &s.data);
    }
}

impl eframe::App for Viewer {
    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        let ctx = ui.ctx().clone();
        self.drive_screenshots(&ctx);
        egui::Panel::top("bar").show(ui, |ui| {
            ui.horizontal(|ui| {
                let mut selected = self.current;
                egui::ComboBox::from_id_salt("sample").selected_text(&self.samples[selected].name).show_ui(ui, |ui| {
                    for (i, s) in self.samples.iter().enumerate() {
                        ui.selectable_value(&mut selected, i, &s.name);
                    }
                });
                if selected != self.current {
                    self.select(selected);
                }
                egui::widgets::global_theme_preference_buttons(ui);
                if let Ok(doc) = &self.doc {
                    if doc.needs_browser() {
                        ui.label(format!(
                            "needs a browser: scripts={} external={} unsupported={:?}",
                            doc.uses_scripts,
                            doc.external_resources.len(),
                            doc.unsupported
                        ));
                    }
                    if doc.is_blank() {
                        ui.label("(nothing to show natively)");
                    }
                }
                if let Some(l) = &self.last_link {
                    ui.label(format!("clicked: {l}"));
                }
            });
        });
        egui::CentralPanel::default().show(ui, |ui| match &self.doc {
            Ok(doc) => {
                let mut clicked = None;
                doc.show(ui, &mut |href: &str| clicked = Some(href.to_string()));
                if clicked.is_some() {
                    self.last_link = clicked;
                }
            }
            Err(e) => {
                ui.colored_label(egui::Color32::RED, e.to_string());
            }
        });
    }
}

impl Viewer {
    fn drive_screenshots(&mut self, ctx: &egui::Context) {
        let Some(shots) = &mut self.shots else { return };
        let total = self.samples.len() * 2;
        if shots.requested {
            if shots.done.load(Ordering::SeqCst) > shots.step {
                shots.step += 1;
                shots.requested = false;
                shots.frames = 0;
                if shots.step >= total {
                    ctx.send_viewport_cmd(egui::ViewportCommand::Close);
                    return;
                }
                let (sample, dark) = (shots.step / 2, shots.step % 2 == 1);
                ctx.set_theme(if dark { egui::Theme::Dark } else { egui::Theme::Light });
                if sample != self.current {
                    self.select(sample);
                }
            }
            ctx.request_repaint();
            return;
        }
        shots.frames += 1;
        ctx.request_repaint();
        if shots.frames < 8 {
            return;
        }
        shots.requested = true;
        let (sample, dark) = (shots.step / 2, shots.step % 2 == 1);
        let name: String = self.samples[sample]
            .name
            .chars()
            .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '-' })
            .collect();
        let path = shots.dir.join(format!("{sample}-{name}-{}.png", if dark { "dark" } else { "light" }));
        let done = shots.done.clone();
        let repaint = ctx.clone();
        ctx.send_viewport_cmd(egui::ViewportCommand::Screenshot(egui::ScreenshotCallback::new(move |img| {
            let [w, h] = img.size;
            let bytes: Vec<u8> = img.pixels.iter().flat_map(|c| c.to_srgba_unmultiplied()).collect();
            match image::save_buffer(&path, &bytes, w as u32, h as u32, image::ExtendedColorType::Rgba8) {
                Ok(()) => println!("saved {}", path.display()),
                Err(e) => eprintln!("{}: {e}", path.display()),
            }
            done.fetch_add(1, Ordering::SeqCst);
            repaint.request_repaint();
        })));
    }
}

fn main() -> eframe::Result {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut samples = samples();
    if let Some(template) = args.first() {
        let template = std::fs::read_to_string(template).expect("template file");
        let data = match args.get(1) {
            Some(p) => serde_json::from_str(&std::fs::read_to_string(p).expect("data file")).expect("data JSON"),
            None => Value::Null,
        };
        samples.insert(0, Sample { name: args[0].clone(), template, data });
    }
    let shots = std::env::var_os("MERPATI_HTML_SCREENSHOTS").map(|dir| {
        let dir = PathBuf::from(dir);
        std::fs::create_dir_all(&dir).expect("screenshot dir");
        Shots { dir, step: 0, frames: 0, requested: false, done: Arc::new(AtomicUsize::new(0)) }
    });
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default().with_inner_size([960.0, 720.0]).with_title("merpati-html"),
        ..Default::default()
    };
    eframe::run_native(
        "merpati-html-view",
        options,
        Box::new(move |cc| {
            egui_extras::install_image_loaders(&cc.egui_ctx);
            if shots.is_some() {
                cc.egui_ctx.set_theme(egui::Theme::Light);
            }
            let mut v = Viewer {
                samples,
                current: 0,
                doc: Err(Error::Template { message: String::new(), line: None, column: None }),
                last_link: None,
                shots,
            };
            v.select(0);
            Ok(Box::new(v))
        }),
    )
}
