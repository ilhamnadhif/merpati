struct Sample {
    name: String,
    template: String,
    data: Value,
}

/// A small round PNG as base64, to exercise `data:` URIs.
fn png_dot(color: [u8; 3]) -> String {
    use base64::Engine as _;
    let n = 24u32;
    let img = image::RgbaImage::from_fn(n, n, |x, y| {
        let (dx, dy) = (x as f32 - 11.5, y as f32 - 11.5);
        let alpha = if dx * dx + dy * dy <= 11.5 * 11.5 { 255 } else { 0 };
        image::Rgba([color[0], color[1], color[2], alpha])
    });
    let mut bytes = Vec::new();
    img.write_to(&mut std::io::Cursor::new(&mut bytes), image::ImageFormat::Png).expect("encode png");
    base64::engine::general_purpose::STANDARD.encode(bytes)
}

/// A template and its data from `tests/templates`.
fn fixture(name: &str, file: &str, edit: impl FnOnce(&mut Value)) -> Sample {
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/templates/");
    let template = std::fs::read_to_string(format!("{dir}{file}.hbs")).expect("template");
    let mut data: Value =
        serde_json::from_str(&std::fs::read_to_string(format!("{dir}{file}.json")).expect("data")).expect("JSON");
    edit(&mut data);
    Sample { name: name.into(), template, data }
}

