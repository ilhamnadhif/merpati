//! Preview of the visualizer renderer.
//!
//! ```text
//! cargo run -p merpati-html --example view                       # built-in samples
//! cargo run -p merpati-html --example view -- page.hbs data.json # your template
//! MERPATI_HTML_SCREENSHOTS=/tmp/shots cargo run -p merpati-html --example view
//!     # saves a PNG of every sample in light and dark mode, then exits
//! ```

